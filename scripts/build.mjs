// Build steps. Run from anywhere:
//   node scripts/build.mjs graph   data/floor-graph.json -> web/graph.txt + web/floor-graph.json
//   node scripts/build.mjs cli     compile the terminal program to build/router
//   node scripts/build.mjs test    regenerate the graph, then compile and run cpp/tests.cpp
//   node scripts/build.mjs wasm    compile the C++ to web/router.js + web/router.wasm (needs Emscripten)
//   node scripts/build.mjs all     every step above
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const at = (...parts) => path.join(root, ...parts);
const isWin = process.platform === "win32";
const exe = name => (isWin ? name + ".exe" : name);
const CXX_FLAGS = ["-std=c++14", "-O2", "-Wall", "-Wextra"];

function run(cmd, args) {
  console.log(">", path.basename(cmd), args.join(" "));
  const r = spawnSync(cmd, args, { stdio: "inherit", cwd: root, shell: isWin && /\.(bat|cmd)$/i.test(cmd) });
  if (r.error) fail(r.error.message);
  if (r.status !== 0) process.exit(r.status ?? 1);
}
function fail(message) {
  console.error(message);
  process.exit(1);
}

// Expands the one-floor plan into the graph the C++ reads: every floor gets its own copy,
// rooms get their real numbers, and stairs with a step count link each floor to the next.
function graph() {
  const G = JSON.parse(fs.readFileSync(at("data", "floor-graph.json"), "utf8"));
  const FLOORS = G.meta.floors;  // 0 = ground floor
  const ids = new Set(G.nodes.map(n => n.id));
  const problems = [];
  for (const e of G.edges) {
    if (!ids.has(e.from) || !ids.has(e.to)) problems.push(`${e.id}: unknown end ${e.from} or ${e.to}`);
    const w = e.steps ?? e.est;
    if (!Number.isInteger(w) || w < 0) problems.push(`${e.id}: steps must be a whole number, 0 or more`);
  }
  for (const r of G.rooms) if (!ids.has(r.door)) problems.push(`${r.id}: unknown door point ${r.door}`);
  if (problems.length) fail("data/floor-graph.json:\n  " + problems.join("\n  "));

  // Counted steps where we have them; else an estimate in real steps (estSteps, from the counts
  // around a typo); else the drawing estimate scaled to real steps.
  const weight = e => e.steps ?? e.fixed ?? e.estSteps ?? Math.max(1, Math.round(e.est * (G.meta.estFactor ?? 1)));
  const hop = Math.round((G.meta.corridorCrossSteps ?? G.meta.corridorCrossEst) / 2);
  const roomOn = (id, floor) => id[0] + floor + id.slice(2);
  const measured = G.edges.filter(e => e.steps != null).length;
  const allStairs = G.nodes.filter(n => n.kind === "stair");
  const flight = s => s.flightSteps ?? G.meta.stairFlightEst;
  const linked = allStairs.filter(s => flight(s) != null);

  const lines = [
    "# Generated by scripts/build.mjs from data/floor-graph.json. Don't edit by hand.",
    "# One edge per line: placeA placeB steps. Rooms use their real numbers (A006, A106, A206);",
    '# every other place is "<id>@<floor>".',
    `# ${measured} of ${G.edges.length} corridor segments measured, the rest estimated. Room to door point: ${hop} steps.`,
  ];
  for (const f of FLOORS) {
    lines.push("", `# Floor ${f}: corridors, toilets, entries, stair landings`);
    for (const e of G.edges) lines.push(`${e.from}@${f} ${e.to}@${f} ${weight(e)}`);
    lines.push(`# Floor ${f}: rooms`);
    for (const r of G.rooms) lines.push(`${roomOn(r.id, f)} ${r.door}@${f} ${hop}`);
  }
  const counted = allStairs.filter(s => s.flightSteps != null).length;
  lines.push("", `# Stairs between floors: ${linked.length} of ${allStairs.length} linked, ${counted} counted (the rest use the ${G.meta.stairFlightEst}-step estimate)`);
  for (const s of linked)
    for (const f of FLOORS.slice(0, -1)) lines.push(`${s.id}@${f} ${s.id}@${f + 1} ${flight(s)}`);

  fs.mkdirSync(at("web"), { recursive: true });
  fs.writeFileSync(at("web", "graph.txt"), lines.join("\n") + "\n");
  fs.writeFileSync(at("web", "floor-graph.json"), JSON.stringify(G));
  fs.copyFileSync(at("data", "walks.json"), at("web", "walks.json"));  // for the counting form
  const edges = lines.filter(l => l && !l.startsWith("#")).length;
  console.log(`graph: ${edges} edges -> web/graph.txt (${measured}/${G.edges.length} segments measured, ${linked.length}/${allStairs.length} stairs linked)`);
}

function cli() {
  fs.mkdirSync(at("build"), { recursive: true });
  run("g++", [...CXX_FLAGS, "-o", at("build", exe("router")), "cpp/main.cpp", "cpp/graph.cpp"]);
}

function test() {
  graph();
  fs.mkdirSync(at("build"), { recursive: true });
  run("g++", [...CXX_FLAGS, "-o", at("build", exe("tests")), "cpp/tests.cpp", "cpp/graph.cpp", "cpp/wasm_api.cpp"]);
  run(at("build", exe("tests")), ["web/graph.txt"]);
}

function findEmxx() {
  const which = spawnSync(isWin ? "where" : "which", ["em++"], { encoding: "utf8" });
  if (which.status === 0) {
    const hits = which.stdout.split(/\r?\n/).filter(Boolean);
    return (isWin && hits.find(h => /\.bat$/i.test(h))) || hits[0];
  }
  const dir = path.join(process.env.EMSDK || path.join(os.homedir(), "emsdk"), "upstream", "emscripten");
  const local = (isWin ? ["em++.exe", "em++.bat"] : ["em++"]).map(f => path.join(dir, f)).find(p => fs.existsSync(p));
  if (local) return local;
  fail("Emscripten (em++) not found. Install emsdk into ~/emsdk, or set EMSDK to where it is.");
}

function wasm() {
  run(findEmxx(), [
    "-std=c++17", "-O2", "cpp/graph.cpp", "cpp/wasm_api.cpp", "-o", "web/router.js",
    "-sMODULARIZE=1", "-sEXPORT_NAME=createRouter",
    "-sEXPORTED_FUNCTIONS=_load_graph,_find_route", "-sEXPORTED_RUNTIME_METHODS=ccall",
    "-sALLOW_MEMORY_GROWTH=1", "-sSTACK_SIZE=1048576", "-sENVIRONMENT=web,node",
  ]);
}

const steps = { graph, cli, test, wasm, all: () => { test(); cli(); wasm(); } };
const step = steps[process.argv[2]];
if (!step) fail(`usage: node scripts/build.mjs ${Object.keys(steps).join("|")}`);
step();
